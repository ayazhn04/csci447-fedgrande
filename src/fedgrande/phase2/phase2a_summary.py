"""Aggregate all Phase 2A machine outputs into results/phase2/phase2a_summary.json and reports/phase2a_report.md.

Every number in the report is read from the JSON/CSV outputs; nothing is typed by hand.
"""
import json
import os
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))

import pandas as pd  # noqa: E402

from fedgrande.paths import GRANDE_WORKTREES, RESULTS, ROOT  # noqa: E402
from fedgrande.provenance import write_json  # noqa: E402


def md_table(df: pd.DataFrame) -> str:
    """Minimal markdown table (avoids an extra dependency)."""
    df = df.reset_index() if not isinstance(df.index, pd.RangeIndex) else df
    cols = [" / ".join(map(str, c)) if isinstance(c, tuple) else str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def J(p):
    return json.load(open(RESULTS / p))


def main():
    e0a, e0b = J("gate_a/e0a_report.json"), J("gate_a/e0b_report.json")
    b, c, d, ef = J("gate_b/dyads_report.json"), J("gate_c/splits_report.json"), J("gate_d/wave_report.json"), J("gate_ef/gate_ef_summary.json")
    runs = pd.read_csv(RESULTS / "gate_ef" / "runs_table.csv")
    waves = pd.read_csv(RESULTS / "gate_d" / "wave_table.csv")
    proj = pd.read_csv(RESULTS / "gate_ef" / "projections.csv")
    main_run = json.load(open(RESULTS / "gate_ef" / "E_main" / "metrics.json"))
    tests = {e: open(RESULTS / f"tests_{e}.log").read().strip().splitlines()[-1] for e in ("fedgrande-dev", "fedgrande-ref")}
    wt_clean = {k: subprocess.run(["git", "-C", str(v[0]), "status", "--porcelain", "--untracked-files=no"], capture_output=True, text=True).stdout.strip() == ""
                for k, v in GRANDE_WORKTREES.items()}

    gates = {
        "A_E0a_forward_equivalence": bool(e0a["E0a_pass"]),
        "A_E0b_training_sanity": bool(e0b["identical_training"] and e0b["loss_decreased_ref"] and e0b["loss_decreased_dev"]),
        "B_dyads_trustworthy": bool(b["validation_pairs"]["pairs_same_match"] and b["validation_pairs"]["pairs_same_wave"]
                                    and b["validation_groups"]["groups_single_wave"]),
        "C_grouped_split_leak_free": c["C2_dyad_grouped"]["total_dyad_group_overlap"] == 0
                                     and c["C2_dyad_grouped"]["total_test_rows_whose_mirror_is_in_train"] == 0,
        "D_wave_audit_done": d["dyads_crossing_waves"] == 0,
        "E_baseline_trained": main_run["test_at_0.5"]["roc_auc"] > 0.5 and main_run["epochs_completed"] > 1,
        "F_benchmarks_complete": bool((runs.status == "ok").all()),
        "tests_pass": all(t == "OK" for t in tests.values()),
        "third_party_unmodified": all(wt_clean.values()),
    }
    summary = {"gates": gates, "phase2a_pass": all(gates.values()), "tests": tests, "free_disk_gib": round(shutil.disk_usage(os.path.expanduser("~")).free / 2**30, 1)}
    write_json(RESULTS / "phase2a_summary.json", summary)

    v1, v2 = c["C1_rowwise"], c["C2_dyad_grouped"]
    mm = main_run
    L = []
    w = L.append
    w("# Phase 2A report (generated)\n")
    w("Generated by `src/fedgrande/phase2/phase2a_summary.py` from the JSON/CSV outputs in `results/phase2/`. No number below was typed by hand.\n")
    w(f"**Phase 2A gates:** " + ", ".join(f"{k}={'PASS' if v else 'FAIL'}" for k, v in gates.items()) + "\n")
    w("## A. GRANDE version equivalence\n")
    for rec in e0a["cases"]:
        cmp = rec["comparisons"]["canonical/eval_logits"]
        w(f"- E0a `{rec['case']['name']}`: canonical-state eval logits max|Δ|={cmp['max_abs']:.3g}, mean|Δ|={cmp['mean_abs']:.3g}, bitwise={cmp['bitwise_equal']}; "
          f"all compared tensors pass={rec['pass_all_compared_tensors']}; V={rec['selected_variables_dev']}; params={rec['trainable_params_dev']}")
    w(f"- E0b: train-loss curve max|Δ|={e0b['train_loss_curve']['max_abs']}, val-loss max|Δ|={e0b['val_loss_curve']['max_abs']}, "
      f"test-probability max|Δ|={e0b['p_test']['max_abs']}, best epoch ref/dev={e0b['best_epoch_ref']}/{e0b['best_epoch_dev']}, "
      f"test AUC ref/dev={e0b['metrics']['ref']['test_auc']:.4f}/{e0b['metrics']['dev']['test_auc']:.4f}; identical training={e0b['identical_training']}\n")
    w("## B. Dyads\n")
    w(f"- groups: {b['n_groups']}; rows by status: {b['status_rows']}; groups by status: {b['status_groups']}")
    w(f"- validation: {b['validation_pairs']}; {b['validation_groups']}\n")
    w("## C. Leakage\n")
    w(f"- C1 row-wise: test rows whose mirror is in training = {v1['total_test_rows_whose_mirror_is_in_train']} of 8378 "
      f"({v1['total_test_rows_whose_mirror_is_in_train']/8378:.1%}); dyad-group overlaps summed over folds = {v1['total_dyad_group_overlap']}")
    w(f"- C2 dyad-grouped: mirror-in-train = {v2['total_test_rows_whose_mirror_is_in_train']}, group overlap = {v2['total_dyad_group_overlap']}, "
      f"max |fold positive rate − overall| = {v2['max_abs_pos_rate_deviation']:.5f}")
    lk = ef["leakage_contrast_C1"]
    w(f"- model-level diagnostic (E256 d5, one fold): C1 test AUC {lk['auc_all_C1_test']:.4f} vs C2 {lk['auc_C2_same_config']:.4f}; inside C1: AUC mirror-in-train "
      f"{lk['auc_mirror_in_train']:.4f} (n={lk['n_mirror_in_train']}, pos={lk['pos_mirror_in_train']}) vs not {lk['auc_mirror_not_in_train']:.4f} "
      f"(n={lk['n_mirror_not_in_train']}, pos={lk['pos_mirror_not_in_train']}) — descriptive only\n")
    w("## D. Waves\n")
    w(md_table(waves))
    w(f"\n- quantity skew {d['quantity_skew']}; label shift {d['label_shift']}; feature shift {d['feature_shift']}")
    w(f"- protocol: expected_num_interested_in_me fully missing in waves {d['protocol_missingness_shift']['waves_fully_missing']}\n")
    w("## E. First GRANDE 1.0.0 SpeedDating baseline (C2 outer fold 0, seed 42)\n")
    w(f"- label: {mm['label']}")
    w(f"- test ROC-AUC {mm['test_at_0.5']['roc_auc']:.4f}; macro-F1@0.5 {mm['test_at_0.5']['macro_f1']:.4f}; accuracy@0.5 {mm['test_at_0.5']['accuracy']:.4f}; "
      f"confusion [[tn,fp],[fn,tp]] {mm['test_at_0.5']['confusion_matrix_[[tn,fp],[fn,tp]]']}")
    w(f"- validation-selected threshold {mm['val_selected_threshold']}: test macro-F1 {mm['test_at_val_threshold']['macro_f1']:.4f}")
    w(f"- best epoch {mm['best_epoch']} of {mm['epochs_completed']}; fit {mm['fit_seconds']:.1f}s; predict {mm['predict_test_seconds']:.2f}s; "
      f"peak RSS {mm['peak_rss_mb_process']:.0f} MB; params {mm['trainable_parameters']}; V {mm['selected_variables_per_estimator']} of {mm['network_input_features_after_preprocessing']} inputs\n")
    w("## F. Runtime\n")
    w(md_table(runs.drop(columns=["status"])))
    w("\n**Projected (not measured)** GRANDE-only compute, assumptions A1–A5 in `results/phase2/gate_ef/gate_ef_summary.json`:\n")
    w(md_table(proj.pivot_table(index=["config"], columns=["protocol", "partitions"], values="grande_hours_projected").round(1)))
    w(f"\n## Tests\n\n{tests}\n")
    os.makedirs(ROOT / "reports", exist_ok=True)
    (ROOT / "reports" / "phase2a_report.md").write_text("\n".join(L) + "\n")
    print(json.dumps(summary, indent=1))


if __name__ == "__main__":
    main()
