"""Generate reports/phase2b_report.md and results/phase2b/phase2b_summary.json from saved outputs only."""
import json
import os
import shutil
import subprocess
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))

import pandas as pd  # noqa: E402

from fedgrande.paths import GRANDE_WORKTREES, ROOT  # noqa: E402
from fedgrande.phase2.phase2a_summary import md_table  # noqa: E402
from fedgrande.provenance import write_json  # noqa: E402

R = ROOT / "results" / "phase2b"
S = R / "summary"


def fmt(v):
    return f"{v['mean']:+.4f} ± {v['sd']:.4f}"


def main(tag):
    summ = json.load(open(S / f"summary_{tag}.json"))
    gaps = json.load(open(S / f"gaps_{tag}.json"))
    oof = pd.read_csv(S / f"oof_summary_{tag}.csv")
    disp = pd.read_csv(S / f"per_wave_dispersion_summary_{tag}.csv")
    cons = pd.read_csv(S / f"consensus_summary_{tag}.csv")
    rel = json.load(open(S / f"consensus_vs_gap_{tag}.json"))
    loc = pd.read_csv(S / f"local_model_consensus_{tag}.csv")
    comm = pd.read_csv(S / f"communication_{tag}.csv")
    rt = pd.read_csv(S / f"runtime_{tag}.csv")
    sv = pd.read_csv(S / f"structure_vs_central_{tag}.csv").groupby(["method", "partition"]).frac_nodes_same_feature_as_central_mean.agg(["mean", "std"]).reset_index()
    prep = json.load(open(R / "prepare" / "prepare_report.json"))
    pnat = pd.read_csv(R / "prepare" / "partition_natural.csv")
    piid = pd.read_csv(R / "prepare" / "partition_iid.csv")
    pc = json.load(open(R / "prep_check" / "prep_check.json"))
    stock = json.load(open(R / "stock_reference" / "summary.json"))
    dpath = R / "prepare" / "partition_dirichlet0.1.json"
    wave_detail = pd.read_csv(S / f"per_wave_mean_over_seeds_{tag}.csv")
    tests = {p.name: p.read_text().strip().splitlines()[-1] for p in sorted(R.glob("tests_*.log"))}
    wt_clean = all(subprocess.run(["git", "-C", str(v[0]), "status", "--porcelain", "--untracked-files=no"], capture_output=True, text=True).stdout.strip() == ""
                   for v in GRANDE_WORKTREES.values())

    L = []
    w = L.append
    w("# Phase 2B report (generated)\n")
    w("Generated by `src/fedgrande/phase2b/report.py` from `results/phase2b/`. No number below is typed by hand. Protocol: `reports/PHASE2B_PROTOCOL.md`.\n")
    w(f"- jobs aggregated: {summ['n_jobs']}; project commits in results: {summ['project_commits_in_results']}; config sha256: {summ['config_sha256']}")
    w(f"- total job compute: {summ['total_compute_hours']:.2f} h; third-party GRANDE worktrees unmodified: {wt_clean}; tests: {tests}\n")
    w("## Preprocessing and features\n")
    f0 = prep["folds"][0]
    w(f"- raw features {prep['raw_feature_schema']['n_raw']} ({prep['raw_feature_schema']['n_numeric']} numeric, {prep['raw_feature_schema']['n_categorical']} nominal); "
      f"encoded dim per fold {[f['encoded_dim'] for f in prep['folds']]}; one-hot columns {f0['one_hot_columns']}; MISSING columns {f0['missing_indicator_columns']}; "
      f"unseen val/test categories {[ (f['unseen_or_unk_val'], f['unseen_or_unk_test']) for f in prep['folds']]}\n")
    w("## Partitions\n")
    w("Natural (client = wave):\n")
    w(md_table(pnat))
    w("\nIID size-matched (partition seed 7):\n")
    w(md_table(piid))
    if dpath.exists():
        dj = json.load(open(dpath))
        w(f"\nDirichlet α=0.1 (amendment A1): max size deviation {dj['max_abs_size_deviation']}, positive rate range [{dj['pos_rate_min']}, {dj['pos_rate_max']}], "
          f"clients with 0 positives {dj['clients_with_zero_pos']}, all-positive clients {dj['clients_all_pos']}, groups crossing clients {dj['leakage_groups_crossing_clients']}\n")
        w(md_table(pd.read_csv(R / "prepare" / "partition_dirichlet0.1.csv")))
    w("\n## Global pooled-OOF metrics (mean ± SD over 3 seeds)\n")
    w(md_table(oof.round(4)))
    w("\n## Per-fold test metrics (A3; mean over 5 folds per seed, then mean ± SD over seeds)\n")
    w(md_table(pd.read_csv(S / f"per_fold_summary_{tag}.csv").round(4)))
    w("\n## Gaps (per seed on pooled OOF, mean ± SD over seeds)\n")
    for k, v in gaps.items():
        w(f"- {k}: {fmt(v)}")
    wcs = pd.read_csv(S / f"within_client_auc_summary_{tag}.csv")
    w("\n## POST-HOC within-client AUC (amendment A2; own clients with both classes in pooled OOF test rows)\n")
    w(md_table(wcs.round(4)))
    w("\n## Per-wave dispersion (natural waves, pooled OOF per seed; mean and SD over seeds)\n")
    keep = [c for c in disp.columns if c.endswith("_mean") or c in ("method", "partition")]
    w(md_table(disp[keep].round(4)))
    w("\nPer-wave AUC (mean over seeds), all methods:\n")
    w(md_table(wave_detail.pivot_table(index=["wave", "n", "pos"], columns=["method", "partition"], values="auc_mean").round(3)))
    w("\n## Structural consensus (FedAvg GRANDE; mean and SD over fold × seed runs)\n")
    w(md_table(cons.set_index("partition").T.round(4).reset_index().rename(columns={"index": "metric"})))
    fx = pd.read_csv(S / f"consensus_fixed_rounds_summary_{tag}.csv")
    w("\nFixed-round diagnostics (A3):\n")
    w(md_table(fx[[c for c in fx.columns if c in ("partition", "round") or c.endswith("_mean")]].round(4)))
    w(f"\nLocal-only final-model consensus: {loc.round(4).to_dict('records')}")
    w(f"\nFraction of nodes whose final selected feature equals the centralized model's (same fold/seed/init): {sv.round(4).to_dict('records')}")
    w(f"\nConsensus vs per-fold gap (Spearman, descriptive): {json.dumps(rel['relation'])}\n")
    w("## Communication\n")
    w(md_table(comm.round(1)))
    w("\n## Runtime and memory\n")
    w(md_table(rt.round(1)))
    w("\n## Stock-vs-custom preprocessing check (same centralized loop, C2 fold 0, 3 seeds)\n")
    w(md_table(pd.DataFrame(pc["summary"]).round(4)))
    w(f"\nstock LOO-encoded columns: {pc['stock_loo_columns']}; stock numeric imputation value {pc['stock_numeric_impute_value']:.3f} (= mean of first numeric column `{pc['stock_first_numeric_column']}`)\n")
    w("## Stock GRANDE 1.0 reference (not the matched comparator)\n")
    w(f"- per fold: {stock['per_fold']}\n- pooled OOF: {stock['oof_test']}\n")
    (ROOT / "reports" / "phase2b_report.md").write_text("\n".join(L) + "\n")
    write_json(R / "phase2b_summary.json", {"tag": tag, "summary": summ, "gaps": gaps, "free_disk_gib": round(shutil.disk_usage(os.path.expanduser("~")).free / 2**30, 1),
                                            "third_party_unmodified": wt_clean, "tests": tests})
    print("report written")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "core")
